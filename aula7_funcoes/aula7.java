/*
-Funções
   Seja a seguinte sintaxe:


   -Modificadores
   *public
      Significa que o método pode ser acessado de qualquer outra classe.
   *protected
      Mesma classe, mesmo package e subclasses
   *private
      Somente a própria classe
   *Sem modificador
      Mesma classe e mesmo package

   -Modificador Opcional
   *static
      O método pertence à classe, não a um objeto específico.
   *final
      O método não pode ser sobrescrito (override) por uma subclasse.
   *Sem modificador opcional
      O método pertence à classe a um objeto específico.
   *abstract
      Declara um método sem implementação, que deverá ser implementado por uma subclasse.
   *synchronized
      Controla o acesso ao método para evitar que múltiplas threads executem aquele método simultaneamente no mesmo objeto.
   *native
      Indica que a implementação do método está escrita em outra linguagem, normalmente código nativo.

   -Tipo de retorno
      *void
         O método não retorna valor
      *int, double, float, char, boolena, String
         Retorno escrito pela tipagem

   -Observações
      Ela deve retorna o tipo que foi declarada
      A variável criado na função fica no escopo da função

   *Assim temos:
   public static int (int a, int b) {
      <comandos>
      return int
   }
   


*/ 




